# --- item mapping (dataset -> NativeItem dicts) -----------------------------

def _conv_content(raw, lang="en"):
    """ConversationContent dict from a dataset 'conversation' list. ``lang`` picks
    the shown turn language (the other is preserved per-turn under metadata)."""
    other = "de" if lang == "en" else "en"
    return {
        "type": "conversation",
        "messages": [
            {"role": m.get("role", "Klient"),
             "content": m.get(lang) or m.get("en") or m.get("de", ""),
             "metadata": {other: m.get(other, "")}}
            for m in raw
        ],
    }


def _features_from_candidates(cands):
    """NativeFeature dicts (A, B, ...) from dataset candidates (English content)."""
    feats = []
    for idx, c in enumerate(cands):
        feats.append({
            "type": "candidate",
            "content": c.get("en") or c.get("de", ""),
            "generated_by": c.get("generated_by") or c.get("source") or "unknown",
        })
    return feats


def _map_items(eval_type, items, lang="en"):
    """Map a dataset's items to LLARS-Native item dicts for create_scenario_one_shot.

    ``lang`` (en|de) picks the visible item/label/conversation language; the
    other language is preserved in metadata. Default 'en' keeps IJCAI behaviour.
    """
    other = "de" if lang == "en" else "en"
    out = []
    for i, it in enumerate(items, start=1):
        nid = f"{eval_type}_{i}"
        label = it.get(f"label_{lang}") or it.get("label_en") or it.get("label_de") or f"Item {i}"
        meta = {f"content_{other}": it.get(f"content_{other}", ""),
                f"label_{other}": it.get(f"label_{other}", "")}
        if it.get("ground_truth"):
            meta["ground_truth"] = it["ground_truth"]

        if eval_type in ("mail_rating", "communication_comparison"):
            content = _conv_content(it.get("conversation", []), lang)
        else:
            content = it.get(f"content_{lang}", "") or it.get("content_en", "") or it.get("content_de", "") or label

        # source: for AUTHENTICITY the rater must NOT see whether the text is
        # human- or AI-written — that's exactly what they guess. So the visible
        # source is neutral ('unknown', no name) and the gold (source_type +
        # generator) is kept ONLY in metadata for scoring/analysis. For all other
        # types the source is the (human) client text.
        if eval_type == "authenticity":
            stype, sname = "unknown", None
            meta["ground_truth"] = it.get("source_type")          # gold: human|llm
            meta["source_name"] = it.get("source_name")           # gold generator
        else:
            stype, sname = "human", None

        item = {
            "id": nid,
            "label": label,
            "source": {"type": stype, "name": sname},
            "content": content,
            "metadata": meta,
            "features": [],
        }
        if eval_type in ("comparison", "communication_comparison", "ranking"):
            item["features"] = _features_from_candidates(it.get("candidates", []))
        out.append(item)
    return out


