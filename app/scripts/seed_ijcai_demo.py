"""
IJCAI 2026 demo seeder.

Builds ONE shared demo scenario per evaluation type (7 total), each with 20
items, owned by the system account ``ijcai_demo``, and a single configurable
referral link ``/join/ijcai`` that on signup enrols the visitor as ASSESSOR in
all 7 scenarios AND grants read-only manager VIEWER on all 7 (so conference
attendees can both evaluate and watch the live aggregated analysis).

Concept
-------
Shared scenarios (not per-user): everyone who scans the QR rates the SAME 20
items per type, so the Scenario-Manager analysis shows live inter-rater
reliability across all participants — the headline demo of a collaborative
evaluation platform.

Content
-------
Item content is shown in ENGLISH (best for the international IJCAI audience);
the German original is preserved in each item's metadata (``content_de`` /
per-turn ``de``). The evaluation CONFIG (task, dimensions, buckets, labels,
questions, options) is fully bilingual (de/en) and drives the UI chrome, which
switches with the user's language toggle. (To flip content to German, swap the
``en``/``de`` picks in ``_map_items`` — both languages are in the datasets.)

Datasets are generated by the ``ijcai-demo-data`` workflow into
``app/scripts/ijcai_demo/<type>.json`` (7 agents, one per type).

Showcase content beyond evaluation
----------------------------------
Evaluation alone shows only a third of LLARS, so the seeder additionally gives
``ijcai_demo`` two English prompt-engineering prompts ("Structured Situation
Analysis", "Empathic Reply Draft") and two COMPLETED batch-generation jobs
(10 counselling cases x 1 prompt x Mistral 24B + 128B = 20 outputs each). The
canned texts/metadata live in ``app/scripts/ijcai_demo/generation_seed.py``;
the cases are imported from ``db/seeders/demo_video_data.COUNSELLING_CASES``.

Every visitor gets their own editable COPY of the two prompts and read access
to the two jobs. That provisioning happens at registration time and is driven
by ``referral_links.provision_json``, which this seeder writes:

    {"clone_prompt_ids": [<UserPrompt.prompt_id>, ...],
     "share_job_ids":   [<GenerationJob.id>, ...]}

The link also confers the ``ijcai_reviewer`` role (prompt engineering +
generation + all evaluation types, no admin permissions). Visitors who joined
before this was in place are backfilled at the end of every seed run (role +
prompt clones + job shares) — see ``_backfill_demo_accounts``.

End of life
-----------
The demo has a defined end. This seeder sets the link's ``expires_at`` to
``LINK_EXPIRES_AT`` (2026-08-29 23:59:59 local) on every run, after which no NEW
registrations are possible. Existing conference accounts expire independently 7
days after their registration: ``scripts.demo_cleanup.expire_ijcai_accounts``
swaps all their roles for the empty ``demo_expired`` role and archives their
memberships — they can still log in, but nothing is usable any more.

Idempotent throughout: scenarios are matched by name + creator, prompts by
(owner, name), jobs by (name, creator), the referral link is updated in place,
and the backfill re-uses ``ReferralService.provision_demo_content`` which skips
what a user already has — safe to run after every deploy.

Usage:
    docker exec llars_flask_<color> python -m scripts.seed_ijcai_demo
    docker exec llars_flask_<color> python -m scripts.seed_ijcai_demo --reset
"""

