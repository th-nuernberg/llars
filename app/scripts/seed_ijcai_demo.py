def _inject_task(config_json: dict, eval_type: str) -> None:
    """Write the per-type task ('Aufgabe') text where resolveTaskMarkdown reads it.

    Pydantic strips an unknown task_description_markdown from non-comparison
    configs, so we set it at the TOP LEVEL (root.task_description_markdown — a
    resolveTaskMarkdown fallback path) and mirror it into config /
    eval_config.config, covering every read path for every type.
    """
    task = _TASKS.get(eval_type)
    if not task:
        return
    config_json['task_description_markdown'] = task
    if isinstance(config_json.get('config'), dict):
        config_json['config']['task_description_markdown'] = task
    ec = config_json.get('eval_config')
    if isinstance(ec, dict) and isinstance(ec.get('config'), dict):
        ec['config']['task_description_markdown'] = task


# --- prompt engineering showcase --------------------------------------------
#
# Block structure mirrors demo_video_service._build_preseed_prompt_content:
# {"blocks": {<block name>: {"content", "position", "author"}}}. The Prompt
# Engineering UI renders the blocks in ``position`` order and concatenates
# System Prompt + Task Explanation into the system message, while the Data
# Format Explanation block carries the {{subject}} / {{content}} variables that
# batch generation substitutes per source item.

def _build_analysis_prompt_content():
    """Prompt 1: five-section situation analysis of an e-counselling thread.

    Deliberately prescriptive (fixed section names, quotes as evidence, no
    speculation) so that outputs of different models are directly comparable —
    that comparison is what the conference demo is about. The Situation section
    reuses the proven numbered-list-with-quotes wording of the demo-video
    prompt; the four analytical sections are what make the result usable in a
    counselling context.
    """
    return {
        "blocks": {
            "System Prompt": {
                "content": (
                    "You are an analytical assistant for professionals in psychosocial online "
                    "counselling. You read email exchanges between help-seeking clients and "
                    "counsellors and turn them into a structured, factual case analysis that a "
                    "counsellor can act on. You never diagnose, and you never invent information "
                    "that is not in the thread."
                ),
                "position": 0,
                "author": OWNER_USERNAME,
            },
            "Task Explanation": {
                "content": (
                    "Analyse the email thread and return exactly these five sections, in this "
                    "order, each with its heading in bold:\n\n"
                    "**Situation** — up to three numbered points describing the client's current "
                    "life circumstances. Each point: at most two sentences, followed by direct "
                    "quotes from the thread as evidence, placed after a dash. Cover housing, "
                    "family relationships, children (age, development, health), work or "
                    "education, health, and social conflicts where the thread mentions them.\n"
                    "**Emotional State** — how the client and any children involved are doing "
                    "emotionally, grounded in what they say and do, not in assumptions.\n"
                    "**Needs** — three to five bullet points, the most urgent first.\n"
                    "**Risk Assessment** — one of Low / Moderate / Elevated, followed by the "
                    "concrete indicators and any protective factors. Name explicitly when the "
                    "thread contains no indication of danger.\n"
                    "**Suggested Approach** — two to four numbered, concrete next steps for the "
                    "counsellor.\n\n"
                    "Rules:\n"
                    "- Use only facts from the thread; mark nothing as certain that is not stated\n"
                    "- No diagnoses, no medical or legal advice\n"
                    "- No introductory or closing phrases — start with the first heading\n"
                    "- When counselling parents, always include the children's situation"
                ),
                "position": 1,
                "author": OWNER_USERNAME,
            },
            "Data Format Explanation": {
                "content": (
                    "Subject: {{subject}}\n\n"
                    "Email thread:\n"
                    "{{content}}\n\n"
                    "The thread is given in chronological order, alternating between the client "
                    "and the counsellor. Return only the five sections."
                ),
                "position": 2,
                "author": OWNER_USERNAME,
            },
        }
    }


def _build_reply_prompt_content():
    """Prompt 2: draft a supportive counsellor reply to the client's last message.

    Complements prompt 1 on the SAME cases: analysis vs. generation on identical
    input is the contrast visitors compare in the batch-generation results view.
    The constraints (length, one open question, no diagnoses) keep the drafts
    comparable across models and safe to show at a public booth.
    """
    return {
        "blocks": {
            "System Prompt": {
                "content": (
                    "You are an experienced counsellor in psychosocial online counselling. You "
                    "write warm, respectful replies to help-seeking clients: plain language, no "
                    "jargon, no false reassurance. You take what the client says seriously and "
                    "you never diagnose or give medical or legal advice."
                ),
                "position": 0,
                "author": OWNER_USERNAME,
            },
            "Task Explanation": {
                "content": (
                    "Draft the counsellor's reply to the client's LATEST message in the thread.\n\n"
                    "The reply must:\n"
                    "- open by acknowledging and validating what the client feels, without "
                    "platitudes\n"
                    "- refer to at least two concrete details from the latest message, so the "
                    "client can tell they were read\n"
                    "- offer one or two practical, realistic next steps the client could take in "
                    "the coming days\n"
                    "- end with exactly one open question that invites the client to write back\n\n"
                    "Rules:\n"
                    "- roughly 150 to 250 words, written directly to the client in the second person\n"
                    "- no diagnoses, no medical or legal advice; signpost to appropriate services "
                    "instead\n"
                    "- do not promise outcomes, and do not minimise the situation\n"
                    "- return only the reply text, with no salutation line and no signature"
                ),
                "position": 1,
                "author": OWNER_USERNAME,
            },
            "Data Format Explanation": {
                "content": (
                    "Subject: {{subject}}\n\n"
                    "Email thread:\n"
                    "{{content}}\n\n"
                    "The thread is given in chronological order, alternating between the client "
                    "and the counsellor. The last client message is the one you reply to."
                ),
                "position": 2,
                "author": OWNER_USERNAME,
            },
        }
    }


def _get_block(content: dict, name: str) -> str:
    """Text of a named prompt block ('' when the block is missing)."""
    block = (content or {}).get("blocks", {}).get(name, {})
    return block.get("content", "") if isinstance(block, dict) else ""


def _render_system(content: dict) -> str:
    """System message a generation run would build from a prompt's blocks."""
    parts = [_get_block(content, "System Prompt"), _get_block(content, "Task Explanation")]
    return "\n\n".join(p for p in parts if p)


def _render_user(content: dict, case: dict) -> str:
    """User message for one source item ({{subject}}/{{content}} substituted)."""
    tpl = _get_block(content, "Data Format Explanation")
    if not tpl:
        return f"Subject: {case['subject']}\n\n{case['content']}"
    return tpl.replace("{{subject}}", case["subject"]).replace("{{content}}", case["content"])


def _seed_prompts(db, owner) -> tuple:
    """Create/refresh the two showcase prompts owned by ``ijcai_demo``.

    Idempotent by (user_id, name): an existing prompt is reused, and its content
    is overwritten when the template here has changed — otherwise a deploy that
    improves the wording would leave the demo account on the old version while
    new visitors get clones of it.

    Returns ``(prompts_by_name, actions)``.
    """
    from db.models import UserPrompt

    templates = [
        (PROMPT_ANALYSIS_NAME, _build_analysis_prompt_content()),
        (PROMPT_REPLY_NAME, _build_reply_prompt_content()),
    ]

    prompts, actions = {}, []
    for name, content in templates:
        prompt = UserPrompt.query.filter_by(user_id=owner.id, name=name).first()
        if not prompt:
            prompt = UserPrompt(user_id=owner.id, name=name, content=content)
            db.session.add(prompt)
            db.session.flush()
            actions.append(f"Created prompt '{name}' (id={prompt.prompt_id})")
        elif (prompt.content or {}) != content:
            prompt.content = content
            actions.append(f"Updated prompt '{name}' (id={prompt.prompt_id}) to current template")
        else:
            actions.append(f"Prompt '{name}' already up to date (id={prompt.prompt_id})")
        prompts[name] = prompt

    db.session.commit()
    return prompts, actions


def _seed_generation_jobs(db, prompts: dict) -> tuple:
    """Create the two COMPLETED batch-generation jobs owned by ``ijcai_demo``.

    Each job is a 10 cases x 1 prompt x 2 models matrix (20 outputs) with canned
    content — deterministic and independent of any live LLM key, so re-seeding
    after a deploy never costs tokens or fails on a rotated key. Idempotent by
    (name, created_by): an existing job is left untouched (like the demo-video
    seeder), because rebuilding it would orphan the shares handed to visitors.

    Returns ``(job_ids, actions)``; ``job_ids`` is empty when a required model
    is missing (seeding is skipped gracefully in that case).
    """
    from db.models.generation import (
        GeneratedOutput, GeneratedOutputStatus, GenerationJob, GenerationJobStatus,
    )
    from db.models.llm_model import LLMModel
    from db.seeders.demo_video_data import COUNSELLING_CASES
    from scripts.ijcai_demo.generation_seed import (
        MODEL_128B, MODEL_24B, PROMPT_ANALYSIS, PROMPT_REPLY,
        OUTPUT_METADATA, build_sample_outputs, job_totals,
    )

    actions = []
    model_24b = LLMModel.query.filter_by(model_id=MODEL_24B_ID).first()
    model_128b = LLMModel.query.filter_by(model_id=MODEL_128B_ID).first()
    if not model_24b or not model_128b:
        missing = [mid for mid, m in ((MODEL_24B_ID, model_24b), (MODEL_128B_ID, model_128b)) if not m]
        logger.warning("LLM model(s) %s not found — skipping generation job seeding", missing)
        actions.append(f"Skipped generation jobs: LLM model(s) not found ({', '.join(missing)})")
        return [], actions

    sample_outputs = build_sample_outputs()
    models = [(model_24b, MODEL_24B), (model_128b, MODEL_128B)]
    now = datetime.utcnow()

    specs = [
        (JOB_ANALYSIS_NAME, PROMPT_ANALYSIS_NAME, PROMPT_ANALYSIS,
         "IJCAI 2026 demo batch: structured five-section case analysis of 10 English "
         "counselling threads, generated with Mistral Small 24B and Mistral Medium 128B."),
        (JOB_REPLY_NAME, PROMPT_REPLY_NAME, PROMPT_REPLY,
         "IJCAI 2026 demo batch: empathic counsellor reply drafts for the same 10 English "
         "counselling threads, generated with Mistral Small 24B and Mistral Medium 128B."),
    ]

    job_ids = []
    for job_name, prompt_name, prompt_key, description in specs:
        existing = GenerationJob.query.filter_by(name=job_name, created_by=OWNER_USERNAME).first()
        if existing:
            job_ids.append(existing.id)
            actions.append(f"Job '{job_name}' already exists (id={existing.id})")
            continue

        prompt_content = prompts[prompt_name].content or {}
        totals = job_totals(prompt_key)
        total_outputs = len(COUNSELLING_CASES) * len(models)

        # Timestamps sit in the past so the job reads as a finished run rather
        # than as something that is still going (the UI shows relative times).
        job = GenerationJob(
            name=job_name,
            description=description,
            status=GenerationJobStatus.COMPLETED,
            config_json={
                "mode": "matrix",
                "sources": {"type": "manual", "items": COUNSELLING_CASES},
                "prompts": [{"template_name": prompt_name}],
                "llm_models": [model_24b.model_id, model_128b.model_id],
                "generation_params": {"temperature": 0.7, "max_tokens": 700},
            },
            total_items=total_outputs,
            completed_items=total_outputs,
            failed_items=0,
            total_tokens=totals["total_tokens"],
            total_cost_usd=totals["total_cost_usd"],
            created_by=OWNER_USERNAME,
            created_at=now - timedelta(days=1, hours=3),
            started_at=now - timedelta(days=1, hours=3),
            completed_at=now - timedelta(days=1, hours=2, minutes=48),
        )
        db.session.add(job)
        db.session.flush()

        rendered_system = _render_system(prompt_content)
        output_idx = 0
        for case_idx, case in enumerate(COUNSELLING_CASES):
            rendered_user = _render_user(prompt_content, case)
            for model, model_key in models:
                meta = OUTPUT_METADATA[prompt_key][model_key][case_idx]
                db.session.add(GeneratedOutput(
                    job_id=job.id,
                    llm_model_id=model.id,
                    llm_model_name=model.model_id,
                    prompt_variant_name=prompt_name,
                    # source_index is how the results view groups outputs by case.
                    prompt_variables_json={
                        "source_index": case_idx,
                        "source_subject": case["subject"],
                    },
                    generated_content=sample_outputs[prompt_key][model_key][case_idx],
                    rendered_system_prompt=rendered_system,
                    rendered_user_prompt=rendered_user,
                    status=GeneratedOutputStatus.COMPLETED,
                    input_tokens=meta["input_tokens"],
                    output_tokens=meta["output_tokens"],
                    total_cost_usd=meta["cost_usd"],
                    processing_time_ms=meta["processing_time_ms"],
                    attempt_count=1,
                    created_at=now - timedelta(days=1, hours=3),
                    completed_at=now - timedelta(days=1, hours=3) + timedelta(seconds=30 * output_idx),
                ))
                output_idx += 1

        db.session.commit()
        job_ids.append(job.id)
        actions.append(f"Created job '{job_name}' (id={job.id}) with {total_outputs} outputs")

    return job_ids, actions


def _backfill_demo_accounts(db, link) -> list:
    """Give already-registered visitors the role and content the link now grants.

    The link originally handed out the 'evaluator' role and no prompts/jobs, so
    accounts created before this seeder version would silently keep the smaller
    demo. Candidates are the deterministic demo usernames of this link
    (``demo-<slug>-*``, see referral_routes._demo_username_from_email) plus every
    username recorded in referral_registrations for this link — the latter also
    covers existing users who redeemed the code instead of registering.

    Provisioning itself is delegated to ReferralService.provision_demo_content
    (same code path as a live registration, idempotent). That method is added by
    the referral-provisioning work; while it is not deployed yet the backfill
    logs a warning and only fixes the roles, so the seeder never crashes.
    """
    from db.models import User
    from db.models.referral import ReferralRegistration
    from services.permission_service import PermissionService
    from services.referral_service import ReferralService

    usernames = {
        row.username for row in
        ReferralRegistration.query.filter_by(link_id=link.id).all()
    }
    usernames.update(
        u.username for u in
        User.query.filter(User.username.like(f"demo-{LINK_SLUG}-%")).all()
    )
    usernames.discard(OWNER_USERNAME)
    if not usernames:
        return []

    can_provision = hasattr(ReferralService, "provision_demo_content")
    if not can_provision:
        logger.warning(
            "ReferralService.provision_demo_content is missing — backfilling roles only. "
            "Re-run this seeder after the referral provisioning is deployed."
        )

    checked, roles_assigned, roles_unresolved, provisioned, failed = 0, 0, 0, 0, 0
    prompts_cloned, jobs_shared = 0, 0
    for username in sorted(usernames):
        user = User.query.filter_by(username=username).first()
        if not user:
            continue  # registration row without an account (deleted user)
        checked += 1
        try:
            # assign_role is idempotent (returns True when the row already
            # exists) and returns False when the role itself is unknown.
            if PermissionService.assign_role(
                username=username,
                role_name=LINK_ROLE_NAME,
                admin_username="ijcai_demo_seeder",
            ):
                roles_assigned += 1
            else:
                roles_unresolved += 1
            if can_provision:
                # Never raises and commits itself; returns a per-user summary.
                summary = ReferralService.provision_demo_content(user, link) or {}
                prompts_cloned += summary.get("prompts_cloned", 0)
                jobs_shared += summary.get("jobs_shared", 0)
                provisioned += 1
        except Exception as exc:
            # One broken account must not abort the backfill for the others.
            db.session.rollback()
            failed += 1
            logger.warning("Backfill failed for %s: %s", username, exc)

    if roles_unresolved:
        logger.warning(
            "Role '%s' could not be assigned to %d account(s) — does the role exist?",
            LINK_ROLE_NAME, roles_unresolved,
        )

    actions = [
        f"Backfill: {checked} existing demo account(s) checked "
        f"({len(usernames)} candidate username(s)), "
        f"role '{LINK_ROLE_NAME}' ensured for {roles_assigned}"
    ]
    if roles_unresolved:
        actions.append(f"Backfill: role '{LINK_ROLE_NAME}' unresolved for {roles_unresolved} account(s)")
    if can_provision:
        actions.append(
            f"Backfill: provisioning applied to {provisioned} account(s) — "
            f"{prompts_cloned} prompt clone(s), {jobs_shared} job share(s) created"
        )
    else:
        actions.append("Backfill: provisioning skipped (ReferralService.provision_demo_content missing)")
    if failed:
        actions.append(f"Backfill: {failed} account(s) failed (see log)")
    return actions


