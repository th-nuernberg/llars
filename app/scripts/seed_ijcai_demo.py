def seed_ijcai_demo(reset: bool = False) -> dict:
    from db import db
    from db.models import RatingScenarios, ReferralCampaign
    from db.models.referral import ReferralLink
    from schemas.api_v1.scenario_api import ScenarioCreateRequest
    from services.api_v1_scenario_service import create_scenario_one_shot, _build_config_json

    owner = _ensure_owner(db)
    db.session.commit()

    begin = datetime.utcnow()
    # Fixed end date instead of the old "begin + 8 weeks": the relative window
    # silently expired on 2026-08-02 (seeded 2026-06-07) and an ended scenario
    # is status 'completed' — which the EvaluationHub HIDES from non-owners
    # (scenario_manager_api status computation, utcnow-based), i.e. conference
    # visitors would have seen NOTHING. Config-as-code like LINK_EXPIRES_AT:
    # refreshed on every seed run, also on the reuse path below.
    end = SCENARIO_END_AT
    scenario_ids = []
    actions = []

    for eval_type, name, cfg_builder in TYPES:
        display_name = name["en"]
        items = _map_items(eval_type, _load_dataset(eval_type))
        payload = ScenarioCreateRequest(
            name=display_name,
            description=("IJCAI 2026 live demo — " + name["de"]),
            eval_config=cfg_builder(),
            items={"items": items},
            assessors=[],  # participants join via the referral link, not pre-assigned
            begin=begin,
            end=end,
        )

        existing = (RatingScenarios.query
                    .filter_by(scenario_name=display_name, created_by=OWNER_USERNAME)
                    .first())
        if existing and reset:
            # Deep delete via the shared service — a bare session.delete() dies
            # on the cascade-less per-item evaluation relationships (NOT NULL
            # scenario_id → IntegrityError, seen on prod 2026-08-16) and would
            # leave the scenario's EvaluationItems behind as orphans that the
            # import service re-uses by chat_id, resurrecting stale content on
            # the re-seed right below.
            from services.scenario_deletion_service import delete_scenario_deep
            delete_scenario_deep(existing)
            db.session.commit()
            existing = None

        if existing:
            # Re-runnable: refresh the config (task texts, dimensions, labels,
            # buckets, …) on the existing scenario WITHOUT recreating it — keeps
            # the scenario id, its items, and the referral link intact. Items are
            # not re-imported (only config changes are picked up on re-run).
            cj = _build_config_json(payload)
            _inject_task(cj, eval_type)
            existing.config_json = cj
            # Refresh the evaluation window too (config-as-code): the original
            # relative end date expired mid-August and made every scenario
            # 'completed' → hidden from visitors. See SCENARIO_END_AT.
            existing.end = SCENARIO_END_AT
            if existing.begin and existing.begin > datetime.utcnow():
                existing.begin = begin  # never leave a scenario in 'draft'
            db.session.add(existing)
            db.session.commit()
            scenario_ids.append(existing.id)
            logger.info("Scenario '%s' (id=%s) — config refreshed", display_name, existing.id)
            continue

        scenario = create_scenario_one_shot(payload, OWNER_USERNAME)
        # Overlay the top-level task text (Pydantic strips task_description_markdown
        # from non-comparison configs; resolveTaskMarkdown also reads it at root).
        cj = dict(scenario.config_json or {})
        _inject_task(cj, eval_type)
        scenario.config_json = cj
        db.session.add(scenario)
        db.session.commit()
        scenario_ids.append(scenario.id)
        logger.info("Created scenario '%s' (id=%s, %d items)", display_name, scenario.id, len(items))

    # Prompt-engineering + batch-generation showcase owned by ijcai_demo. Seeded
    # BEFORE the link, because the link's provision_json references their ids.
    prompts, prompt_actions = _seed_prompts(db, owner)
    actions.extend(prompt_actions)
    for line in prompt_actions:
        logger.info(line)

    job_ids, job_actions = _seed_generation_jobs(db, prompts)
    actions.extend(job_actions)
    for line in job_actions:
        logger.info(line)

    # Referral link: enrol into all 7 as assessor + viewer, configurable signup.
    campaign = ReferralCampaign.query.filter_by(name=CAMPAIGN_NAME).first()
    if not campaign:
        campaign = ReferralCampaign(name=CAMPAIGN_NAME, status="active", created_by=OWNER_USERNAME)
        db.session.add(campaign)
        db.session.flush()

    link = ReferralLink.query.filter_by(slug=LINK_SLUG).first()
    if not link:
        link = ReferralLink(campaign_id=campaign.id, slug=LINK_SLUG, created_by=OWNER_USERNAME)
        db.session.add(link)
    link.campaign_id = campaign.id
    # ijcai_reviewer instead of evaluator: conference visitors also need prompt
    # engineering and batch generation, but must NOT get the extra powers of
    # 'researcher' (referral link creation, anonymisation). The registration
    # route re-checks this against ALLOWED_REFERRAL_ROLES and falls back to
    # 'evaluator' if the role is not allowlisted there.
    link.role_name = LINK_ROLE_NAME
    link.label = "IJCAI 2026 Demo"
    link.is_active = True
    # Hard end of life for NEW sign-ups — see LINK_EXPIRES_AT.
    link.expires_at = LINK_EXPIRES_AT
    link.target_scenario_ids = scenario_ids
    link.viewer_scenario_ids = scenario_ids
    link.signup_mode = "email"   # conference default: QR -> email -> in
    link.default_locale = "en"   # IJCAI demo is English by default (join + profile)
    link.collect_email = True
    link.collect_email_optional = False
    link.collect_display_name = True

    # Per-registration provisioning: every visitor gets an editable CLONE of the
    # two prompts and a SHARE on the two jobs (cloning 40 output rows per visitor
    # would be wasteful, and the shared results are what makes live IRR-style
    # comparison possible). Contract: {"clone_prompt_ids": [...],
    # "share_job_ids": [...]} — consumed by ReferralService.provision_demo_content.
    provision = {
        "clone_prompt_ids": [prompts[n].prompt_id for n in (PROMPT_ANALYSIS_NAME, PROMPT_REPLY_NAME)],
        "share_job_ids": job_ids,
    }
    if hasattr(link, "provision_json"):
        link.provision_json = json.dumps(provision)
        actions.append(f"Link provisioning set: {provision}")
    else:
        # Column not deployed yet — never fail the seed run over it.
        logger.warning(
            "ReferralLink.provision_json is missing — prompt/job provisioning NOT stored. "
            "Re-run this seeder after the referral provisioning migration is deployed."
        )
        actions.append("Link provisioning skipped (ReferralLink.provision_json missing)")
    db.session.commit()

    # Visitors who joined before the role/provisioning existed get the same
    # content retroactively (idempotent — see _backfill_demo_accounts).
    backfill_actions = _backfill_demo_accounts(db, link)
    actions.extend(backfill_actions)
    for line in backfill_actions:
        logger.info(line)

    result = {
        "scenario_ids": scenario_ids,
        "prompt_ids": provision["clone_prompt_ids"],
        "job_ids": job_ids,
        "link_slug": LINK_SLUG,
        "link_code": link.code,
        "link_role": link.role_name,
        "join_url": f"/join/{link.slug or link.code}",
        "signup_mode": link.signup_mode,
        "link_expires_at": link.expires_at.isoformat() if link.expires_at else None,
        "actions": actions,
    }
    logger.info("IJCAI demo seeded: %s", result)
    return result


